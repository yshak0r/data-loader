-- Scope: same rule as the load (validated rows, data-capture warehouses), per company
IF OBJECT_ID('tempdb..#WH')   IS NOT NULL DROP TABLE #WH;
IF OBJECT_ID('tempdb..#QDEL') IS NOT NULL DROP TABLE #QDEL;

SELECT DISTINCT K.COMPANY_CODE, K.WAREHOUSE
INTO #WH
FROM KAS_DC_LOADS K
WHERE K.STATUS_FLAG = 'V'
  AND K.WAREHOUSE IN (SELECT WC.WAREHOUSE FROM WAREHOUSE_CONTROLS WC WHERE WC.DATA_CAPTURE_IN_USE = 'Y');

-- Quality doc lines in the in-scope warehouses (captured BEFORE anything is deleted)
SELECT Q.COMPANY_CODE, Q.QUALITY_DOC_NBR, Q.QUALITY_DOC_LINE_NBR
INTO #QDEL
FROM IC_QUALITY_DOC_LINES Q
JOIN #WH W ON W.COMPANY_CODE = Q.COMPANY_CODE AND W.WAREHOUSE = Q.WAREHOUSE;

-- 1. Quality doc line details (by company + doc + line)
DELETE D
FROM IC_QUALITY_DOC_LINE_DETAILS D
JOIN #QDEL X ON X.COMPANY_CODE = D.COMPANY_CODE
            AND X.QUALITY_DOC_NBR = D.QUALITY_DOC_NBR
            AND X.QUALITY_DOC_LINE_NBR = D.QUALITY_DOC_LINE_NBR;

-- 2. Quality doc lines (has WAREHOUSE, so no bin match is needed)
DELETE Q
FROM IC_QUALITY_DOC_LINES Q
JOIN #QDEL X ON X.COMPANY_CODE = Q.COMPANY_CODE
            AND X.QUALITY_DOC_NBR = Q.QUALITY_DOC_NBR
            AND X.QUALITY_DOC_LINE_NBR = Q.QUALITY_DOC_LINE_NBR;

-- 3. Quality docs: only those touched above that now have no lines left
--    (a doc can have lines in other warehouses, so it must not be removed while they exist)
DELETE QD
FROM IC_QUALITY_DOCS QD
WHERE EXISTS (SELECT 1 FROM #QDEL X
              WHERE X.COMPANY_CODE = QD.COMPANY_CODE AND X.QUALITY_DOC_NBR = QD.QUALITY_DOC_NBR)
  AND NOT EXISTS (SELECT 1 FROM IC_QUALITY_DOC_LINES Q
                  WHERE Q.COMPANY_CODE = QD.COMPANY_CODE AND Q.QUALITY_DOC_NBR = QD.QUALITY_DOC_NBR);

-- 4. Plate line details (plate lookup by company + plate id, plates still exist at this point)
DELETE D
FROM DC_LICENSE_PLATE_LINE_DETAILS D
JOIN DC_LICENSE_PLATES P ON P.COMPANY_CODE = D.COMPANY_CODE AND P.DC_LICENSE_PLATE_ID = D.DC_LICENSE_PLATE_ID
JOIN #WH W ON W.COMPANY_CODE = P.COMPANY_CODE AND W.WAREHOUSE = P.WAREHOUSE;

-- 5. Plate lines
DELETE L
FROM DC_LICENSE_PLATE_LINES L
JOIN DC_LICENSE_PLATES P ON P.COMPANY_CODE = L.COMPANY_CODE AND P.DC_LICENSE_PLATE_ID = L.DC_LICENSE_PLATE_ID
JOIN #WH W ON W.COMPANY_CODE = P.COMPANY_CODE AND W.WAREHOUSE = P.WAREHOUSE;

-- 6. Plates (after their lines and details)
DELETE P
FROM DC_LICENSE_PLATES P
JOIN #WH W ON W.COMPANY_CODE = P.COMPANY_CODE AND W.WAREHOUSE = P.WAREHOUSE;

-- 7. Inventory levels and bin details (company + warehouse)
DELETE T FROM BIN_LOCATION_DETAILS T JOIN #WH W ON W.COMPANY_CODE = T.COMPANY_CODE AND W.WAREHOUSE = T.WAREHOUSE;
DELETE T FROM IC_BIN_DETAIL_STATUS T JOIN #WH W ON W.COMPANY_CODE = T.COMPANY_CODE AND W.WAREHOUSE = T.WAREHOUSE;
DELETE T FROM IC_LOT_STATUS        T JOIN #WH W ON W.COMPANY_CODE = T.COMPANY_CODE AND W.WAREHOUSE = T.WAREHOUSE;
DELETE T FROM IC_PRODUCT_STATUS    T JOIN #WH W ON W.COMPANY_CODE = T.COMPANY_CODE AND W.WAREHOUSE = T.WAREHOUSE;
-- (see note: for packaged parts consider zeroing IC_QUANTITY instead of deleting)

