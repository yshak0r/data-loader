-- ============================================================================
-- CLEAR_SO_TABLES.SQL
-- Whole-order cleanup of the Sales Orders created by the LOAD_SO_*.sql scripts.
--
-- Scope: orders on FIN.KAS_SO_LOADS with STATUS_FLAG='V' AND an ORDER_NUMBER,
-- whose header still matches the staged customer + customer reference.
-- The ENTIRE order (lines/details/qtys/history, export details/notes + header) is deleted.
-- STATUS_FLAG='P' rows and orders not created by the loader are never touched.
--
-- Staging rows (FIN.KAS_SO_LOADS) are NOT modified: ORDER_NUMBER is kept so the
-- loader reuses it.
--
-- FRONTEND-FRIENDLY: no variables, no temp tables, no BEGIN/COMMIT/RETURN, no
-- semicolons inside statements. The frontend runs each ';'-terminated statement
-- separately inside its own transaction, so nothing may depend on state carried
-- from one statement to the next. If a safety check fails, THROW raises an error
-- and the frontend rolls everything back.
-- ============================================================================

SET NOCOUNT ON;

-- 1. Safety check: no invoice rows on the target orders
IF EXISTS (
    SELECT 1
    FROM FIN.SALES_ORDER_INVOICES I
    WHERE EXISTS (
        SELECT 1
        FROM FIN.KAS_SO_LOADS K
        JOIN FIN.SALES_ORDER_HEADERS H
          ON H.COMPANY_CODE = K.COMPANY_CODE AND H.DIVISION = K.DIVISION
         AND H.ORDER_NUMBER = K.ORDER_NUMBER
         AND H.CUSTOMER_NUMBER = K.CUSTOMER_NUMBER
         AND H.CUSTOMER_REFERENCE = K.CUSTOMER_REFERENCE
        WHERE K.STATUS_FLAG = 'V' AND K.ORDER_NUMBER IS NOT NULL
          AND K.COMPANY_CODE = I.COMPANY_CODE AND K.DIVISION = I.DIVISION
          AND K.ORDER_NUMBER = I.ORDER_NUMBER))
THROW 50001, 'CLEAR_SO_TABLES: one or more target sales orders have invoice rows. Cleanup aborted; handle invoiced orders manually.', 1;

-- 2. Safety check: nothing picked / despatched / invoiced
IF EXISTS (
    SELECT 1
    FROM FIN.SALES_ORDER_LINE_QTYS Q
    WHERE (ISNULL(Q.QTY_DESPATCHED, 0) <> 0
        OR ISNULL(Q.QTY_INVOICED, 0) <> 0
        OR ISNULL(Q.IC_QTY_PICKED, 0) <> 0
        OR ISNULL(Q.IC_QTY_IN_DESPATCH, 0) <> 0)
      AND EXISTS (
        SELECT 1
        FROM FIN.KAS_SO_LOADS K
        JOIN FIN.SALES_ORDER_HEADERS H
          ON H.COMPANY_CODE = K.COMPANY_CODE AND H.DIVISION = K.DIVISION
         AND H.ORDER_NUMBER = K.ORDER_NUMBER
         AND H.CUSTOMER_NUMBER = K.CUSTOMER_NUMBER
         AND H.CUSTOMER_REFERENCE = K.CUSTOMER_REFERENCE
        WHERE K.STATUS_FLAG = 'V' AND K.ORDER_NUMBER IS NOT NULL
          AND K.COMPANY_CODE = Q.COMPANY_CODE AND K.DIVISION = Q.DIVISION
          AND K.ORDER_NUMBER = Q.ORDER_NUMBER))
THROW 50002, 'CLEAR_SO_TABLES: one or more target sales orders already have picked/despatched/invoiced quantities. Cleanup aborted; handle them manually.', 1;

-- 3. Delete child rows, then lines, then header (headers last: the criteria need them)
DELETE T
FROM FIN.SALES_ORDER_LINE_DETAIL_QTYS T
WHERE EXISTS (
    SELECT 1
    FROM FIN.KAS_SO_LOADS K
    JOIN FIN.SALES_ORDER_HEADERS H
      ON H.COMPANY_CODE = K.COMPANY_CODE AND H.DIVISION = K.DIVISION
     AND H.ORDER_NUMBER = K.ORDER_NUMBER
     AND H.CUSTOMER_NUMBER = K.CUSTOMER_NUMBER
     AND H.CUSTOMER_REFERENCE = K.CUSTOMER_REFERENCE
    WHERE K.STATUS_FLAG = 'V' AND K.ORDER_NUMBER IS NOT NULL
      AND K.COMPANY_CODE = T.COMPANY_CODE AND K.DIVISION = T.DIVISION
      AND K.ORDER_NUMBER = T.ORDER_NUMBER);

