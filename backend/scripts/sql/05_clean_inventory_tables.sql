-- ============================================================================
-- CLEAR TABLES - NON-POPULATED STAGING RECORDS ONLY
-- ----------------------------------------------------------------------------
-- Removes the inventory data that belongs to staging rows which are NOT yet
-- populated (STATUS_FLAG V or F), so they can be validated/loaded again.
-- Rows with STATUS_FLAG = 'P' are never cleaned, and every key they use is
-- protected: nothing is deleted if a populated row also uses it.
--
-- Record by record (company + plate + line, bin/lot/part/status keys),
-- NOT warehouse by warehouse.
--
-- IC_PRODUCT_STATUS is the exception to "removes": its rows are kept and all its quantity fields are reset to 0, so the
-- QOH row required by status transfers (QC/QR -> QOH) is never lost.
--
-- Also clears what the loader writes beyond the inventory tables (steps 11-18):
--   history    : IC_LOT_TRACE, DC_LICENSE_PLATE_HISTORY, IC_MOVEMENTS,
--                INV_TRANSACTION_DETAILS, INV_TRANSACTION_LINES, INV_TRANSACTIONS
--
-- TOOL-FRIENDLY: no DECLARE, no table variables, no BEGIN/COMMIT/ROLLBACK.
-- The DELETE statements run in the SAME ORDER as the old script so the UI
-- breakdown (quality docs first, then plates, then inventory) is unchanged.
-- ============================================================================
IF OBJECT_ID('tempdb..#S')     IS NOT NULL DROP TABLE #S;
IF OBJECT_ID('tempdb..#P')     IS NOT NULL DROP TABLE #P;
IF OBJECT_ID('tempdb..#SL')    IS NOT NULL DROP TABLE #SL;
IF OBJECT_ID('tempdb..#QLINK') IS NOT NULL DROP TABLE #QLINK;
IF OBJECT_ID('tempdb..#QDEL')  IS NOT NULL DROP TABLE #QDEL;
IF OBJECT_ID('tempdb..#HL')    IS NOT NULL DROP TABLE #HL;
IF OBJECT_ID('tempdb..#LOTS')  IS NOT NULL DROP TABLE #LOTS;
IF OBJECT_ID('tempdb..#LOG')   IS NOT NULL DROP TABLE #LOG;

-- One row per deleted row (filled by the OUTPUT clause of each DELETE below)
CREATE TABLE #LOG (TARGET_TABLE VARCHAR(60) NOT NULL);

-- ---- Scope: staging rows that are NOT populated and CAN have a footprint ----
-- V = validated (may be partly loaded by an interrupted run)
-- F = failed to load
-- E and blank rows are deliberately excluded: they were never loaded and their
-- keys can match real inventory.
SELECT K.GEM_DBKEY, K.COMPANY_CODE, K.WAREHOUSE,
       ISNULL(K.BIN_LOCATION, '')  AS BIN_LOCATION,
       K.DC_LICENSE_PLATE_ID, K.DC_LICENSE_PLATE_LINE, K.PART_CODE,
       ISNULL(K.IC_LOT_NUMBER, '') AS IC_LOT_NUMBER,
       K.IC_STATUS_CODE
INTO #S
FROM KAS_DC_LOADS K
WHERE K.STATUS_FLAG IN ('V', 'F')
  AND K.WAREHOUSE IN (SELECT WC.WAREHOUSE FROM WAREHOUSE_CONTROLS WC WHERE WC.DATA_CAPTURE_IN_USE = 'Y');

-- ---- Protected: the populated rows (already loaded by a previous run) -------
SELECT K.COMPANY_CODE, K.WAREHOUSE,
       ISNULL(K.BIN_LOCATION, '')  AS BIN_LOCATION,
       K.DC_LICENSE_PLATE_ID, K.DC_LICENSE_PLATE_LINE, K.PART_CODE,
       ISNULL(K.IC_LOT_NUMBER, '') AS IC_LOT_NUMBER,
       K.IC_STATUS_CODE
INTO #P
FROM KAS_DC_LOADS K
WHERE K.STATUS_FLAG = 'P';

-- ---- Plate lines to remove: in scope AND not also used by a populated row ----
SELECT DISTINCT S.COMPANY_CODE, S.DC_LICENSE_PLATE_ID, S.DC_LICENSE_PLATE_LINE
INTO #SL
FROM #S S
WHERE S.DC_LICENSE_PLATE_LINE IS NOT NULL
  AND NOT EXISTS (SELECT 1 FROM #P P
                  WHERE P.COMPANY_CODE = S.COMPANY_CODE
                    AND P.DC_LICENSE_PLATE_ID = S.DC_LICENSE_PLATE_ID
                    AND P.DC_LICENSE_PLATE_LINE = S.DC_LICENSE_PLATE_LINE);

-- Quality doc + line each removable plate line points to (captured BEFORE any delete).
-- Quality doc number = ORIG_SOURCE_MODULE + ORIGINAL_DOCUMENT_NUMBER, line = ORIGINAL_DOCUMENT_LINE
SELECT DISTINCT D.COMPANY_CODE,
       CONCAT(D.ORIG_SOURCE_MODULE, D.ORIGINAL_DOCUMENT_NUMBER) AS QUALITY_DOC_NBR,
       TRY_CONVERT(INT, D.ORIGINAL_DOCUMENT_LINE)               AS QUALITY_DOC_LINE_NBR
INTO #QLINK
FROM DC_LICENSE_PLATE_LINE_DETAILS D
JOIN #SL X ON X.COMPANY_CODE = D.COMPANY_CODE
          AND X.DC_LICENSE_PLATE_ID = D.DC_LICENSE_PLATE_ID
          AND X.DC_LICENSE_PLATE_LINE = D.DC_LICENSE_PLATE_LINE
WHERE NULLIF(LTRIM(RTRIM(D.ORIGINAL_DOCUMENT_NUMBER)), '') IS NOT NULL
  AND TRY_CONVERT(INT, D.ORIGINAL_DOCUMENT_LINE) IS NOT NULL;

-- Quality doc lines safe to delete: no plate line detail OUTSIDE the lines being
-- removed still points to them (computed up front, so the delete order can match the UI).
SELECT X.COMPANY_CODE, X.QUALITY_DOC_NBR, X.QUALITY_DOC_LINE_NBR
INTO #QDEL
FROM #QLINK X
WHERE NOT EXISTS (SELECT 1 FROM DC_LICENSE_PLATE_LINE_DETAILS D
                  WHERE D.COMPANY_CODE = X.COMPANY_CODE
                    AND CONCAT(D.ORIG_SOURCE_MODULE, D.ORIGINAL_DOCUMENT_NUMBER) = X.QUALITY_DOC_NBR
                    AND TRY_CONVERT(INT, D.ORIGINAL_DOCUMENT_LINE) = X.QUALITY_DOC_LINE_NBR
                    AND NOT EXISTS (SELECT 1 FROM #SL L
                                    WHERE L.COMPANY_CODE = D.COMPANY_CODE
                                      AND L.DC_LICENSE_PLATE_ID = D.DC_LICENSE_PLATE_ID
                                      AND L.DC_LICENSE_PLATE_LINE = D.DC_LICENSE_PLATE_LINE));

-- History keys of the removable plate lines (captured BEFORE the plate lines are deleted).
-- Same keys the loader uses: DC_LICENSE_PLATE_LINES.DOC_REFERENCE + DOC_LINE (= SEQUENCE),
-- movement code BGNQOH / BGNQR / BGNQC.
SELECT DISTINCT L.COMPANY_CODE, S.WAREHOUSE, L.DC_LICENSE_PLATE_ID, L.DC_LICENSE_PLATE_LINE,
       CONVERT(VARCHAR(30), L.DOC_REFERENCE) AS DOC_REFERENCE,
       TRY_CONVERT(INT, L.DOC_LINE)          AS DOC_LINE
INTO #HL
FROM DC_LICENSE_PLATE_LINES L
JOIN #SL X ON X.COMPANY_CODE = L.COMPANY_CODE
          AND X.DC_LICENSE_PLATE_ID = L.DC_LICENSE_PLATE_ID
          AND X.DC_LICENSE_PLATE_LINE = L.DC_LICENSE_PLATE_LINE
JOIN #S S ON S.COMPANY_CODE = L.COMPANY_CODE
         AND S.DC_LICENSE_PLATE_ID = L.DC_LICENSE_PLATE_ID
         AND S.DC_LICENSE_PLATE_LINE = L.DC_LICENSE_PLATE_LINE
WHERE NULLIF(LTRIM(RTRIM(CONVERT(VARCHAR(30), L.DOC_REFERENCE))), '') IS NOT NULL
  AND TRY_CONVERT(INT, L.DOC_LINE) IS NOT NULL;

-- Lots of in-scope rows that no populated row uses (candidates for lot master cleanup)
SELECT DISTINCT S.COMPANY_CODE, S.WAREHOUSE, S.PART_CODE, S.IC_LOT_NUMBER
INTO #LOTS
FROM #S S
WHERE S.IC_LOT_NUMBER <> ''
  AND NOT EXISTS (SELECT 1 FROM #P P
                  WHERE P.COMPANY_CODE = S.COMPANY_CODE AND P.WAREHOUSE = S.WAREHOUSE
                    AND P.PART_CODE = S.PART_CODE AND P.IC_LOT_NUMBER = S.IC_LOT_NUMBER);

-- 1. Quality doc line details
DELETE D
OUTPUT 'IC_QUALITY_DOC_LINE_DETAILS' INTO #LOG (TARGET_TABLE)
FROM IC_QUALITY_DOC_LINE_DETAILS D
JOIN #QDEL X ON X.COMPANY_CODE = D.COMPANY_CODE
            AND X.QUALITY_DOC_NBR = D.QUALITY_DOC_NBR
            AND X.QUALITY_DOC_LINE_NBR = D.QUALITY_DOC_LINE_NBR;

-- 2. Quality doc lines
DELETE Q
OUTPUT 'IC_QUALITY_DOC_LINES' INTO #LOG (TARGET_TABLE)
FROM IC_QUALITY_DOC_LINES Q
JOIN #QDEL X ON X.COMPANY_CODE = Q.COMPANY_CODE
            AND X.QUALITY_DOC_NBR = Q.QUALITY_DOC_NBR
            AND X.QUALITY_DOC_LINE_NBR = Q.QUALITY_DOC_LINE_NBR;

-- 3. Quality docs: only the ones touched above that now have no lines left
DELETE QD
OUTPUT 'IC_QUALITY_DOCS' INTO #LOG (TARGET_TABLE)
FROM IC_QUALITY_DOCS QD
WHERE EXISTS (SELECT 1 FROM #QLINK X
              WHERE X.COMPANY_CODE = QD.COMPANY_CODE AND X.QUALITY_DOC_NBR = QD.QUALITY_DOC_NBR)
  AND NOT EXISTS (SELECT 1 FROM IC_QUALITY_DOC_LINES Q
                  WHERE Q.COMPANY_CODE = QD.COMPANY_CODE AND Q.QUALITY_DOC_NBR = QD.QUALITY_DOC_NBR);

-- 4. Plate line details
DELETE D
OUTPUT 'DC_LICENSE_PLATE_LINE_DETAILS' INTO #LOG (TARGET_TABLE)
FROM DC_LICENSE_PLATE_LINE_DETAILS D
JOIN #SL X ON X.COMPANY_CODE = D.COMPANY_CODE
          AND X.DC_LICENSE_PLATE_ID = D.DC_LICENSE_PLATE_ID
          AND X.DC_LICENSE_PLATE_LINE = D.DC_LICENSE_PLATE_LINE;

-- 5. Plate lines
DELETE L
OUTPUT 'DC_LICENSE_PLATE_LINES' INTO #LOG (TARGET_TABLE)
FROM DC_LICENSE_PLATE_LINES L
JOIN #SL X ON X.COMPANY_CODE = L.COMPANY_CODE
          AND X.DC_LICENSE_PLATE_ID = L.DC_LICENSE_PLATE_ID
          AND X.DC_LICENSE_PLATE_LINE = L.DC_LICENSE_PLATE_LINE;

-- 6. Plates: only those of in-scope rows that now have no lines left
--    (a plate that still has populated lines keeps its header)
DELETE P
OUTPUT 'DC_LICENSE_PLATES' INTO #LOG (TARGET_TABLE)
FROM DC_LICENSE_PLATES P
WHERE EXISTS (SELECT 1 FROM #S S
              WHERE S.COMPANY_CODE = P.COMPANY_CODE AND S.DC_LICENSE_PLATE_ID = P.DC_LICENSE_PLATE_ID)
  AND NOT EXISTS (SELECT 1 FROM DC_LICENSE_PLATE_LINES L
                  WHERE L.COMPANY_CODE = P.COMPANY_CODE AND L.DC_LICENSE_PLATE_ID = P.DC_LICENSE_PLATE_ID);

-- 7. Inventory levels and bin details.
--    A row is deleted only if an in-scope row uses its key AND no populated row does.
DELETE T
OUTPUT 'BIN_LOCATION_DETAILS' INTO #LOG (TARGET_TABLE)
FROM BIN_LOCATION_DETAILS T
WHERE EXISTS (SELECT 1 FROM #S S
              WHERE S.BIN_LOCATION <> ''
                AND T.COMPANY_CODE = S.COMPANY_CODE AND T.WAREHOUSE = S.WAREHOUSE
                AND T.BIN_LOCATION = S.BIN_LOCATION AND T.PART_CODE = S.PART_CODE
                AND ISNULL(T.IC_LOT_NUMBER, '') = S.IC_LOT_NUMBER)
  AND NOT EXISTS (SELECT 1 FROM #P P
                  WHERE P.BIN_LOCATION <> ''
                    AND T.COMPANY_CODE = P.COMPANY_CODE AND T.WAREHOUSE = P.WAREHOUSE
                    AND T.BIN_LOCATION = P.BIN_LOCATION AND T.PART_CODE = P.PART_CODE
                    AND ISNULL(T.IC_LOT_NUMBER, '') = P.IC_LOT_NUMBER);

DELETE T
OUTPUT 'IC_BIN_DETAIL_STATUS' INTO #LOG (TARGET_TABLE)
FROM IC_BIN_DETAIL_STATUS T
WHERE EXISTS (SELECT 1 FROM #S S
              WHERE S.BIN_LOCATION <> ''
                AND T.COMPANY_CODE = S.COMPANY_CODE AND T.WAREHOUSE = S.WAREHOUSE
                AND T.BIN_LOCATION = S.BIN_LOCATION AND T.PART_CODE = S.PART_CODE
                AND ISNULL(T.IC_LOT_NUMBER, '') = S.IC_LOT_NUMBER
                AND T.IC_STATUS_CODE = S.IC_STATUS_CODE)
  AND NOT EXISTS (SELECT 1 FROM #P P
                  WHERE P.BIN_LOCATION <> ''
                    AND T.COMPANY_CODE = P.COMPANY_CODE AND T.WAREHOUSE = P.WAREHOUSE
                    AND T.BIN_LOCATION = P.BIN_LOCATION AND T.PART_CODE = P.PART_CODE
                    AND ISNULL(T.IC_LOT_NUMBER, '') = P.IC_LOT_NUMBER
                    AND T.IC_STATUS_CODE = P.IC_STATUS_CODE);

DELETE T
OUTPUT 'IC_LOT_STATUS' INTO #LOG (TARGET_TABLE)
FROM IC_LOT_STATUS T
WHERE EXISTS (SELECT 1 FROM #S S
              WHERE S.IC_LOT_NUMBER <> ''
                AND T.COMPANY_CODE = S.COMPANY_CODE AND T.WAREHOUSE = S.WAREHOUSE
                AND T.PART_CODE = S.PART_CODE AND T.IC_LOT_NUMBER = S.IC_LOT_NUMBER
                AND T.IC_STATUS_CODE = S.IC_STATUS_CODE)
  AND NOT EXISTS (SELECT 1 FROM #P P
                  WHERE P.IC_LOT_NUMBER <> ''
                    AND T.COMPANY_CODE = P.COMPANY_CODE AND T.WAREHOUSE = P.WAREHOUSE
                    AND T.PART_CODE = P.PART_CODE AND T.IC_LOT_NUMBER = P.IC_LOT_NUMBER
                    AND T.IC_STATUS_CODE = P.IC_STATUS_CODE);

-- IC_PRODUCT_STATUS rows are NEVER deleted: every part/warehouse must keep its QOH row (even at 0) so a
-- QC/QR -> QOH transfer can always lock it. The in-scope keys are reset instead: ALL quantity fields go to 0
-- (on hand, picked, in despatch, reserved, awaiting confirm out) the loader adds to / re-creates the quantity
-- on the next run. The log keeps the table name, so the count = rows reset to zero.
UPDATE T
SET T.IC_QUANTITY = 0,
    T.IC_QTY_PICKED = 0,
    T.IC_QTY_IN_DESPATCH = 0,
    T.IC_QTY_RESERVED = 0,
    T.IC_QTY_AWAITING_CONFIRM_OUT = 0
OUTPUT 'IC_PRODUCT_STATUS' INTO #LOG (TARGET_TABLE)
FROM IC_PRODUCT_STATUS T
WHERE (ISNULL(T.IC_QUANTITY, 0) <> 0 OR ISNULL(T.IC_QTY_PICKED, 0) <> 0 OR ISNULL(T.IC_QTY_IN_DESPATCH, 0) <> 0
       OR ISNULL(T.IC_QTY_RESERVED, 0) <> 0 OR ISNULL(T.IC_QTY_AWAITING_CONFIRM_OUT, 0) <> 0)
  AND EXISTS (SELECT 1 FROM #S S
              WHERE T.COMPANY_CODE = S.COMPANY_CODE AND T.WAREHOUSE = S.WAREHOUSE
                AND T.PART_CODE = S.PART_CODE AND T.IC_STATUS_CODE = S.IC_STATUS_CODE)
  AND NOT EXISTS (SELECT 1 FROM #P P
                  WHERE T.COMPANY_CODE = P.COMPANY_CODE AND T.WAREHOUSE = P.WAREHOUSE
                    AND T.PART_CODE = P.PART_CODE AND T.IC_STATUS_CODE = P.IC_STATUS_CODE);

-- 13. Lot trace (one row per plate line: warehouse + doc reference + sequence)
DELETE T
OUTPUT 'IC_LOT_TRACE' INTO #LOG (TARGET_TABLE)
FROM IC_LOT_TRACE T
JOIN #HL X ON X.COMPANY_CODE = T.COMPANY_CODE AND X.WAREHOUSE = T.IC_LT_FROM_DIV_WH_FA
          AND X.DOC_REFERENCE = T.IC_LT_FROM_DOC_PART_JOB AND X.DOC_LINE = T.IC_LT_FROM_LINE_LOT_STAGE
WHERE T.MOVEMENT_CODE IN ('BGNQOH', 'BGNQR', 'BGNQC');

-- 14. Plate history written by the load ('Add New LPN' only other plate history is kept)
DELETE T
OUTPUT 'DC_LICENSE_PLATE_HISTORY' INTO #LOG (TARGET_TABLE)
FROM DC_LICENSE_PLATE_HISTORY T
JOIN #HL X ON X.COMPANY_CODE = T.COMPANY_CODE AND X.DC_LICENSE_PLATE_ID = T.DC_LICENSE_PLATE_ID
          AND X.DC_LICENSE_PLATE_LINE = T.DC_LICENSE_PLATE_LINE
          AND X.DOC_REFERENCE = T.DOC_REFERENCE AND X.DOC_LINE = T.DOC_LINE
WHERE T.UPDATE_ACTION = 'Add New LPN';

-- 15. Inventory movements (the loader stores the sequence in DOCUMENT_LINE)
DELETE T
OUTPUT 'IC_MOVEMENTS' INTO #LOG (TARGET_TABLE)
FROM IC_MOVEMENTS T
JOIN #HL X ON X.COMPANY_CODE = T.COMPANY_CODE AND X.DOC_REFERENCE = T.DOCUMENT_NUMBER
          AND X.DOC_LINE = T.DOCUMENT_LINE
WHERE T.MOVEMENT_CODE IN ('BGNQOH', 'BGNQR', 'BGNQC');

-- 16. Transaction details
DELETE T
OUTPUT 'INV_TRANSACTION_DETAILS' INTO #LOG (TARGET_TABLE)
FROM INV_TRANSACTION_DETAILS T
JOIN #HL X ON X.COMPANY_CODE = T.COMPANY_CODE AND X.DOC_REFERENCE = T.DOC_REFERENCE
          AND X.DOC_LINE = T.SEQUENCE
WHERE T.MOVEMENT_CODE IN ('BGNQOH', 'BGNQR', 'BGNQC');

-- 17. Transaction lines
DELETE T
OUTPUT 'INV_TRANSACTION_LINES' INTO #LOG (TARGET_TABLE)
FROM INV_TRANSACTION_LINES T
JOIN #HL X ON X.COMPANY_CODE = T.COMPANY_CODE AND X.DOC_REFERENCE = T.DOC_REFERENCE
          AND X.DOC_LINE = T.SEQUENCE
WHERE T.MOVEMENT_CODE IN ('BGNQOH', 'BGNQR', 'BGNQC');

-- 18. Transaction headers: only those touched above that now have no lines left
--     (a header is shared by every record of the same transaction number)
DELETE H
OUTPUT 'INV_TRANSACTIONS' INTO #LOG (TARGET_TABLE)
FROM INV_TRANSACTIONS H
WHERE H.MOVEMENT_CODE IN ('BGNQOH', 'BGNQR', 'BGNQC')
  AND EXISTS (SELECT 1 FROM #HL X
              WHERE X.COMPANY_CODE = H.COMPANY_CODE AND X.DOC_REFERENCE = H.DOC_REFERENCE)
  AND NOT EXISTS (SELECT 1 FROM INV_TRANSACTION_LINES L
                  WHERE L.COMPANY_CODE = H.COMPANY_CODE AND L.MOVEMENT_CODE = H.MOVEMENT_CODE
                    AND L.DOC_REFERENCE = H.DOC_REFERENCE);

-- ============================================================================
-- REPORTS
-- ============================================================================
-- Rows deleted per table (same order as the UI breakdown).
-- IC_PRODUCT_STATUS is the exception: its count is the rows whose quantity was RESET TO 0 (rows are kept).
SELECT V.TARGET_TABLE, COUNT(L.TARGET_TABLE) AS ROWS_DELETED
FROM (VALUES (1, 'IC_QUALITY_DOC_LINE_DETAILS'), (2, 'IC_QUALITY_DOC_LINES'),
             (3, 'IC_QUALITY_DOCS'), (4, 'DC_LICENSE_PLATE_LINE_DETAILS'),
             (5, 'DC_LICENSE_PLATE_LINES'), (6, 'DC_LICENSE_PLATES'),
             (7, 'BIN_LOCATION_DETAILS'), (8, 'IC_BIN_DETAIL_STATUS'),
             (9, 'IC_LOT_STATUS'), (10, 'IC_PRODUCT_STATUS'), (13, 'IC_LOT_TRACE'),
             (14, 'DC_LICENSE_PLATE_HISTORY'), (15, 'IC_MOVEMENTS'), (16, 'INV_TRANSACTION_DETAILS'),
             (17, 'INV_TRANSACTION_LINES'), (18, 'INV_TRANSACTIONS')) V (SORT_NO, TARGET_TABLE)
LEFT JOIN #LOG L ON L.TARGET_TABLE = V.TARGET_TABLE
GROUP BY V.SORT_NO, V.TARGET_TABLE
ORDER BY V.SORT_NO;

-- Things NOT cleaned because a populated row shares them (adjust by hand, otherwise
-- reloading those rows can stop with a duplicate-key error).
SELECT 'DC_LICENSE_PLATE_LINES - same plate+line also used by a populated row' AS not_cleaned, COUNT(*) AS n
FROM (SELECT DISTINCT S.COMPANY_CODE, S.DC_LICENSE_PLATE_ID, S.DC_LICENSE_PLATE_LINE
      FROM #S S
      WHERE EXISTS (SELECT 1 FROM #P P
                    WHERE P.COMPANY_CODE = S.COMPANY_CODE AND P.DC_LICENSE_PLATE_ID = S.DC_LICENSE_PLATE_ID
                      AND P.DC_LICENSE_PLATE_LINE = S.DC_LICENSE_PLATE_LINE)) Z
UNION ALL
SELECT 'IC_QUALITY_DOC_LINES - still referenced by a populated row', COUNT(*)
FROM #QLINK X WHERE NOT EXISTS (SELECT 1 FROM #QDEL Y
                                WHERE Y.COMPANY_CODE = X.COMPANY_CODE AND Y.QUALITY_DOC_NBR = X.QUALITY_DOC_NBR
                                  AND Y.QUALITY_DOC_LINE_NBR = X.QUALITY_DOC_LINE_NBR)
UNION ALL
SELECT 'BIN_LOCATION_DETAILS - key shared with a populated row', COUNT(*)
FROM BIN_LOCATION_DETAILS T
WHERE EXISTS (SELECT 1 FROM #S S WHERE S.BIN_LOCATION <> '' AND T.COMPANY_CODE = S.COMPANY_CODE
                AND T.WAREHOUSE = S.WAREHOUSE AND T.BIN_LOCATION = S.BIN_LOCATION AND T.PART_CODE = S.PART_CODE
                AND ISNULL(T.IC_LOT_NUMBER, '') = S.IC_LOT_NUMBER)
  AND EXISTS (SELECT 1 FROM #P P WHERE P.BIN_LOCATION <> '' AND T.COMPANY_CODE = P.COMPANY_CODE
                AND T.WAREHOUSE = P.WAREHOUSE AND T.BIN_LOCATION = P.BIN_LOCATION AND T.PART_CODE = P.PART_CODE
                AND ISNULL(T.IC_LOT_NUMBER, '') = P.IC_LOT_NUMBER)
UNION ALL
SELECT 'IC_BIN_DETAIL_STATUS - key shared with a populated row', COUNT(*)
FROM IC_BIN_DETAIL_STATUS T
WHERE EXISTS (SELECT 1 FROM #S S WHERE S.BIN_LOCATION <> '' AND T.COMPANY_CODE = S.COMPANY_CODE
                AND T.WAREHOUSE = S.WAREHOUSE AND T.BIN_LOCATION = S.BIN_LOCATION AND T.PART_CODE = S.PART_CODE
                AND ISNULL(T.IC_LOT_NUMBER, '') = S.IC_LOT_NUMBER AND T.IC_STATUS_CODE = S.IC_STATUS_CODE)
  AND EXISTS (SELECT 1 FROM #P P WHERE P.BIN_LOCATION <> '' AND T.COMPANY_CODE = P.COMPANY_CODE
                AND T.WAREHOUSE = P.WAREHOUSE AND T.BIN_LOCATION = P.BIN_LOCATION AND T.PART_CODE = P.PART_CODE
                AND ISNULL(T.IC_LOT_NUMBER, '') = P.IC_LOT_NUMBER AND T.IC_STATUS_CODE = P.IC_STATUS_CODE)
UNION ALL
SELECT 'IC_LOT_STATUS - key shared with a populated row', COUNT(*)
FROM IC_LOT_STATUS T
WHERE EXISTS (SELECT 1 FROM #S S WHERE S.IC_LOT_NUMBER <> '' AND T.COMPANY_CODE = S.COMPANY_CODE
                AND T.WAREHOUSE = S.WAREHOUSE AND T.PART_CODE = S.PART_CODE AND T.IC_LOT_NUMBER = S.IC_LOT_NUMBER
                AND T.IC_STATUS_CODE = S.IC_STATUS_CODE)
  AND EXISTS (SELECT 1 FROM #P P WHERE P.IC_LOT_NUMBER <> '' AND T.COMPANY_CODE = P.COMPANY_CODE
                AND T.WAREHOUSE = P.WAREHOUSE AND T.PART_CODE = P.PART_CODE AND T.IC_LOT_NUMBER = P.IC_LOT_NUMBER
                AND T.IC_STATUS_CODE = P.IC_STATUS_CODE)
UNION ALL
SELECT 'PART_BATCHES - lot kept (inventory remains or populated row uses it)', COUNT(*)
FROM PART_BATCHES B
WHERE EXISTS (SELECT 1 FROM #S S WHERE S.IC_LOT_NUMBER <> '' AND B.COMPANY_CODE = S.COMPANY_CODE
                AND B.WAREHOUSE = S.WAREHOUSE AND B.PART_CODE = S.PART_CODE AND B.IC_LOT_NUMBER = S.IC_LOT_NUMBER)
UNION ALL
SELECT 'INV_TRANSACTIONS - header kept (other lines still use it)', COUNT(*)
FROM INV_TRANSACTIONS H
WHERE H.MOVEMENT_CODE IN ('BGNQOH', 'BGNQR', 'BGNQC')
  AND EXISTS (SELECT 1 FROM #HL X WHERE X.COMPANY_CODE = H.COMPANY_CODE AND X.DOC_REFERENCE = H.DOC_REFERENCE)
UNION ALL
SELECT 'IC_PRODUCT_STATUS - key shared with a populated row', COUNT(*)
FROM IC_PRODUCT_STATUS T
WHERE EXISTS (SELECT 1 FROM #S S WHERE T.COMPANY_CODE = S.COMPANY_CODE AND T.WAREHOUSE = S.WAREHOUSE
                AND T.PART_CODE = S.PART_CODE AND T.IC_STATUS_CODE = S.IC_STATUS_CODE)
  AND EXISTS (SELECT 1 FROM #P P WHERE T.COMPANY_CODE = P.COMPANY_CODE AND T.WAREHOUSE = P.WAREHOUSE
                AND T.PART_CODE = P.PART_CODE AND T.IC_STATUS_CODE = P.IC_STATUS_CODE);

