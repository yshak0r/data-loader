-- One quality doc per company + part + lot + status.
-- Numbering below follows ROSS GET_NEW_NBR: SOURCE_MODULE + the selected
-- IC_TRANSACTION_TYPES counter, then increment and validate against
-- (COMPANY_CODE, IC_STATUS_CODE, QUALITY_DOC_NBR) in IC_QUALITY_DOCS.
CREATE TABLE #QD_POT
(
    COMPANY_CODE       VARCHAR(50)  NOT NULL,
    PART_CODE          VARCHAR(100) NOT NULL,
    IC_LOT_NUMBER      VARCHAR(100) NOT NULL,
    IC_STATUS_CODE     VARCHAR(10)  NOT NULL,
    QUALITY_DOC_NBR    VARCHAR(100) NULL
);

INSERT INTO #QD_POT (COMPANY_CODE, PART_CODE, IC_LOT_NUMBER, IC_STATUS_CODE)
SELECT DISTINCT
       CONVERT(VARCHAR(50), COMPANY_CODE),
       CONVERT(VARCHAR(100), PART_CODE),
       CONVERT(VARCHAR(100), IC_LOT_NUMBER),
       CONVERT(VARCHAR(10), IC_STATUS_CODE)
FROM #QSRC_POT;

DECLARE @Q_COMPANY_CODE  VARCHAR(50);
DECLARE @Q_STATUS_CODE   VARCHAR(10);
DECLARE @Q_PART_CODE     VARCHAR(100);
DECLARE @Q_LOT_NUMBER    VARCHAR(100);
DECLARE @Q_TTYPE         VARCHAR(50);
DECLARE @Q_COUNTER       BIGINT;
DECLARE @Q_CANDIDATE     VARCHAR(100);
DECLARE @Q_MANUAL_FLAG   VARCHAR(20);
DECLARE @Q_ROW_COUNT     INT;
DECLARE @Q_ATTEMPTS      INT;

DECLARE QD_NUMBER_CURSOR CURSOR LOCAL FAST_FORWARD FOR
    SELECT COMPANY_CODE, IC_STATUS_CODE, PART_CODE, IC_LOT_NUMBER
    FROM #QD_POT
    ORDER BY COMPANY_CODE, IC_STATUS_CODE, PART_CODE, IC_LOT_NUMBER;

OPEN QD_NUMBER_CURSOR;
FETCH NEXT FROM QD_NUMBER_CURSOR
INTO @Q_COMPANY_CODE, @Q_STATUS_CODE, @Q_PART_CODE, @Q_LOT_NUMBER;

WHILE @@FETCH_STATUS = 0
BEGIN
    -- For QC/QR, ROSS uses the status code as TRANSACTION_TYPE.
    -- UD is not included in this loader's QC/QR-only source set.
    SET @Q_TTYPE = @Q_STATUS_CODE;
    SET @Q_ATTEMPTS = 0;
    SET @Q_CANDIDATE = NULL;

    WHILE @Q_CANDIDATE IS NULL
    BEGIN
        SET @Q_ATTEMPTS += 1;
        IF @Q_ATTEMPTS > 1000
        BEGIN
            CLOSE QD_NUMBER_CURSOR;
            DEALLOCATE QD_NUMBER_CURSOR;
            ;THROW 51001, 'Unable to find an unused ROSS quality document number after 1000 attempts.', 1;
        END;

        SET @Q_COUNTER = NULL;
        SET @Q_MANUAL_FLAG = NULL;

        -- UPDLOCK + HOLDLOCK reserve the correct counter row until commit.
        SELECT @Q_COUNTER = TRY_CONVERT(BIGINT, TRANSACTION_NUMBER),
               @Q_MANUAL_FLAG = UPPER(LTRIM(RTRIM(CONVERT(VARCHAR(20), MANUAL_NUMBER))))
        FROM IC_TRANSACTION_TYPES WITH (UPDLOCK, HOLDLOCK)
        WHERE COMPANY_CODE = @Q_COMPANY_CODE
          AND WAREHOUSE = @Q_ALL_WAREHOUSES
          AND TRANSACTION_TYPE = @Q_TTYPE;

        SET @Q_ROW_COUNT = @@ROWCOUNT;
        IF @Q_ROW_COUNT <> 1
        BEGIN
            CLOSE QD_NUMBER_CURSOR;
            DEALLOCATE QD_NUMBER_CURSOR;
            ;THROW 51002, 'Expected exactly one IC_TRANSACTION_TYPES row for company, all-warehouses value, and QC/QR transaction type. Verify @Q_ALL_WAREHOUSES and the counter setup.', 1;
        END;

        IF @Q_COUNTER IS NULL
        BEGIN
            CLOSE QD_NUMBER_CURSOR;
            DEALLOCATE QD_NUMBER_CURSOR;
            ;THROW 51003, 'IC_TRANSACTION_TYPES.TRANSACTION_NUMBER is not a valid integer.', 1;
        END;

        -- Manual numbering requires interactive ROSS input; stop rather than
        -- silently generate an automatic number that ROSS would not generate.
        IF @Q_MANUAL_FLAG IS NULL OR @Q_MANUAL_FLAG NOT IN ('N', 'NO', '0', 'FALSE', '#NO')
        BEGIN
            CLOSE QD_NUMBER_CURSOR;
            DEALLOCATE QD_NUMBER_CURSOR;
            ;THROW 51004, 'The selected IC_TRANSACTION_TYPES row is marked manual or has an unrecognized MANUAL_NUMBER value. Automatic SQL numbering was stopped.', 1;
        END;

        SET @Q_CANDIDATE = CONCAT(@Q_SOURCE_MODULE, CONVERT(VARCHAR(30), @Q_COUNTER));

        -- Match ROSS order: increment the counter before validating the candidate.
        UPDATE IC_TRANSACTION_TYPES
        SET TRANSACTION_NUMBER = @Q_COUNTER + 1
        WHERE COMPANY_CODE = @Q_COMPANY_CODE
          AND WAREHOUSE = @Q_ALL_WAREHOUSES
          AND TRANSACTION_TYPE = @Q_TTYPE;

        IF @@ROWCOUNT <> 1
        BEGIN
            CLOSE QD_NUMBER_CURSOR;
            DEALLOCATE QD_NUMBER_CURSOR;
            ;THROW 51005, 'Failed to increment exactly one IC_TRANSACTION_TYPES counter row.', 1;
        END;

        -- Match VALIDATE_NBR: duplicate check is scoped by company + status + doc number.
        IF EXISTS
        (
            SELECT 1
            FROM IC_QUALITY_DOCS WITH (UPDLOCK, HOLDLOCK)
            WHERE COMPANY_CODE = @Q_COMPANY_CODE
              AND IC_STATUS_CODE = @Q_STATUS_CODE
              AND QUALITY_DOC_NBR = @Q_CANDIDATE
        )
        BEGIN
            SET @Q_CANDIDATE = NULL; -- retry using the next counter value
        END;
    END;

    -- Each #QD_POT row receives its own validated generated document number.
    UPDATE #QD_POT
    SET QUALITY_DOC_NBR = @Q_CANDIDATE
    WHERE COMPANY_CODE = @Q_COMPANY_CODE
