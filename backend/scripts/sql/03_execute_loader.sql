-- ============================================================================
-- POST-PROCESSING: LINK QC/QR QUALITY DOCUMENT REFERENCES
-- CHANGE ADDED: Populate the generated quality-document references after all
-- IC_QUALITY_DOC* records have been inserted, then copy those references back
-- to DC_LICENSE_PLATE_LINES for validated QC/QR load rows only.
--
-- Reference convention for this loader:
--   ORIGINAL_DOCUMENT_NUMBER = generated QUALITY_DOC_NBR
--   ORIGINAL_DOCUMENT_LINE   = generated QUALITY_DOC_LINE_NBR
--
-- NOTE: IC_QUALITY_DOCS is a header table and can have multiple quality lines.
-- Its ORIGINAL_DOCUMENT_LINE is therefore set to the first generated line
-- number for that header. Each DC_LICENSE_PLATE_LINES row receives its own
-- matching line number from DC_LICENSE_PLATE_LINE_DETAILS.
-- ============================================================================

-- CHANGE ADDED: Populate the original-document reference on the quality header.
UPDATE QD
SET QD.ORIGINAL_DOCUMENT_NUMBER = SUBSTRING(CAST(QD.QUALITY_DOC_NBR AS VARCHAR(100)), LEN(@Q_SOURCE_MODULE) + 1, 30),
    QD.ORIGINAL_DOCUMENT_LINE   = QL.FIRST_QUALITY_DOC_LINE_NBR
FROM IC_QUALITY_DOCS QD
INNER JOIN #QD_POT DQ
    ON DQ.COMPANY_CODE = QD.COMPANY_CODE
   AND DQ.QUALITY_DOC_NBR = QD.QUALITY_DOC_NBR
   AND DQ.IC_STATUS_CODE = QD.IC_STATUS_CODE
INNER JOIN
(
    SELECT COMPANY_CODE,
           QUALITY_DOC_NBR,
           MIN(QUALITY_DOC_LINE_NBR) AS FIRST_QUALITY_DOC_LINE_NBR
    FROM #QL_POT
    GROUP BY COMPANY_CODE, QUALITY_DOC_NBR
) QL
    ON QL.COMPANY_CODE = DQ.COMPANY_CODE
   AND QL.QUALITY_DOC_NBR = DQ.QUALITY_DOC_NBR
WHERE QD.IC_STATUS_CODE IN ('QC', 'QR', 'CQC');

-- CHANGE ADDED: Synchronize each validated QC/QR license-plate line with the
-- exact generated quality document and line reference already stored in its
-- DC_LICENSE_PLATE_LINE_DETAILS row. Non-QC/QR rows are not updated.
UPDATE DCL
SET DCL.ORIG_SOURCE_MODULE       = D.ORIG_SOURCE_MODULE,
    DCL.ORIGINAL_DOCUMENT_NUMBER = D.ORIGINAL_DOCUMENT_NUMBER,
    DCL.ORIGINAL_DOCUMENT_LINE   = D.ORIGINAL_DOCUMENT_LINE
FROM DC_LICENSE_PLATE_LINES DCL
INNER JOIN KAS_DC_LOADS K
    ON K.COMPANY_CODE = DCL.COMPANY_CODE
   AND K.DC_LICENSE_PLATE_ID = DCL.DC_LICENSE_PLATE_ID
   AND K.DC_LICENSE_PLATE_LINE = DCL.DC_LICENSE_PLATE_LINE
INNER JOIN PRODUCT_MASTER PM
    ON PM.PART_CODE = K.PART_CODE
INNER JOIN DC_LICENSE_PLATE_LINE_DETAILS D
    ON D.COMPANY_CODE = DCL.COMPANY_CODE
   AND D.DC_LICENSE_PLATE_ID = DCL.DC_LICENSE_PLATE_ID
   AND D.DC_LICENSE_PLATE_LINE = DCL.DC_LICENSE_PLATE_LINE
WHERE K.STATUS_FLAG = 'V'
  AND K.IC_STATUS_CODE IN ('QC', 'QR', 'CQC')
  AND K.WAREHOUSE IN
      (SELECT WC.WAREHOUSE
       FROM WAREHOUSE_CONTROLS WC
       WHERE WC.DATA_CAPTURE_IN_USE = 'Y')
  AND PM.IC_PRODUCT_UOM_CONTROL = 'P'
  AND PM.IC_PACKAGED_PRODUCT = 'N'
  AND D.ORIG_SOURCE_MODULE = @Q_SOURCE_MODULE
  AND ISNULL(D.ORIGINAL_DOCUMENT_NUMBER, '') <> ''
  AND ISNULL(D.ORIGINAL_DOCUMENT_LINE, '') <> '';

